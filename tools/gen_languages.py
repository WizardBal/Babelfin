#!/usr/bin/env python3
"""Generate Engine/Languages/IsoLanguages.g.cs from the pinned tools/data/iso6392.txt.

Usage:
    python tools/gen_languages.py <path to iso6392.txt> [<output .cs>]

The input comes from the Jellyfin server source
(Emby.Server.Implementations/Localization/iso6392.txt, format ``T|B|two|English|French``).
The output is committed; the build never runs Python.

Mapping rules:
  * plain rows -> one entry (TwoLetter may be null; EnglishName = the first name before ';').
    The other ';' names are emitted into ``AlternateNames`` so they still resolve.
  * ``xx-yy`` rows -> Region or Script entries on the base language
    (pt-br -> Region BR, es-419 -> Region 419, zh-hans/zh-cn -> Script Hans,
    zh-hant/zh-tw -> Script Hant, zh-hk -> Script Hant + Region HK).
    Rows that produce a canonical code already emitted (zh-cn after zh-hans and so on) are skipped;
    the raw spelling is covered by AliasTable.Default.
  * alternate names are kept only for plain rows.
  * ``ze`` (Chinese bilingual), the "no language" codes (und, mul, mis, zxx) and ranges (qaa-qtz) are skipped.
"""

import sys
from pathlib import Path

SKIP_T = {"und", "mul", "mis", "zxx"}
SKIP_TWO = {"ze"}
# Subtags that are scripts rather than regions in Jellyfin's two-letter column.
SCRIPT_SUBTAGS = {"hans": ("Hans", None), "hant": ("Hant", None), "cn": ("Hans", None), "tw": ("Hant", None), "hk": ("Hant", "HK")}
# Names that read badly when taken verbatim.
NAME_OVERRIDES = {
    "ell": "Greek",
    "es-419": "Spanish (Latin America)",
}


def cs(value):
    if value is None:
        return "null"
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "plugin" / "src" / "Jellyfin.Plugin.Babelfin" / "Engine" / "Languages" / "IsoLanguages.g.cs"

    entries = []
    alternates = []
    seen_codes = set()
    for raw in src.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line:
            continue
        parts = line.split("|")
        if len(parts) < 4:
            continue
        t, b, two, english = parts[0].strip(), parts[1].strip() or None, parts[2].strip().lower() or None, parts[3].strip()
        if not t or "-" in t or t in SKIP_T or two in SKIP_TWO:
            continue
        names = [n.strip() for n in english.split(";") if n.strip()]
        variety = script = region = None
        if two and "-" in two:
            base, sub = two.split("-", 1)
            if sub in SCRIPT_SUBTAGS:
                script, region = SCRIPT_SUBTAGS[sub]
            elif sub.isdigit():
                region = sub
            else:
                region = sub.upper()
            two_letter = base
        else:
            two_letter = two
        code = (two_letter or t) + ("-" + script if script else "") + ("-" + region if region else "")
        if code.lower() in seen_codes:
            continue
        seen_codes.add(code.lower())
        name = NAME_OVERRIDES.get(code, NAME_OVERRIDES.get(t if code == (two_letter or t) else code, names[0]))
        entries.append((two_letter, t, b, name, variety, script, region))
        # Alternate names only for plain rows: "Spanish; Latin" (es-419) must not make "Latin" mean Spanish.
        for alt in names if code == (two_letter or t) else []:
            if alt != name:
                alternates.append((alt, t))

    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen_languages.py from tools/data/iso6392.txt; upstream provenance is in NOTICE.",
        "// Do not edit by hand: change the generator (or IsoLanguages.Extra.cs) and re-run it.",
        "// </auto-generated>",
        "",
        "#nullable enable",
        "",
        "namespace Jellyfin.Plugin.Babelfin.Engine.Languages;",
        "",
        "/// <summary>The built-in ISO 639 language data (generated part).</summary>",
        "internal static partial class IsoLanguages",
        "{",
        "    /// <summary>Entries generated from Jellyfin's ISO 639-2 table.</summary>",
        "    internal static readonly LanguageEntry[] Entries =",
        "    {",
    ]
    for two_letter, t, b, name, variety, script, region in entries:
        lines.append(f"        new LanguageEntry({cs(two_letter)}, {cs(t)}, {cs(b)}, {cs(name)}, {cs(variety)}, {cs(script)}, {cs(region)}),")
    lines += [
        "    };",
        "",
        "    /// <summary>Further English names from the table (the parts after ';'), as name to ISO 639-2/T code.</summary>",
        "    internal static readonly string[][] AlternateNames =",
        "    {",
    ]
    for alt, code in alternates:
        lines.append(f"        new[] {{ {cs(alt)}, {cs(code)} }},")
    lines += [
        "    };",
        "}",
        "",
    ]
    with out.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(lines))
    print(f"wrote {len(entries)} entries and {len(alternates)} alternate names to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
